// scripts/generateClaimSeed.js
//
// Writes the two generated Milestone 4 migrations from their single sources:
//
//   m4_03_claim_categories.sql  ← utils/claims/defaultCategories.js
//   m4_08_claim_settings.sql    ← the claims.* entries in SETTING_REGISTRY
//
// Generated rather than hand-written so the seed and the code that reads it
// cannot drift. Run it only when one of those sources changes BEFORE the
// migration has been applied anywhere — after that, the migration's checksum is
// recorded and an edited file is refused by scripts/migrate.js, which is the
// point: a live database is changed by a new migration, never by rewriting an
// old one.
//
//   node scripts/generateClaimSeed.js
//
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { DEFAULT_CATEGORIES } from "../utils/claims/defaultCategories.js";
import { SETTING_REGISTRY } from "../models/settingsModel.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.join(here, "..", "migrations");

/** MySQL string literal. Doubles single quotes and backslashes. */
function q(v) {
  if (v === null || v === undefined) return "NULL";
  return `'${String(v).replace(/\\/g, "\\\\").replace(/'/g, "''")}'`;
}
const j = (v) => (v === null || v === undefined ? "NULL" : q(JSON.stringify(v)));

const categoriesSql = `-- ----------------------------------------------------------------------------
-- Milestone 4 — claim categories, sub-categories and what each one asks for.
--
-- GENERATED by scripts/generateClaimSeed.js from utils/claims/defaultCategories.js.
-- Do not edit by hand.
--
-- Everything that differs between claim types is DATA here rather than code in
-- the conversation: the names, the documents requested, the extra questions, the
-- default priority and which plan guarantees the type maps to. The client edits
-- all of it in the admin panel; a new sub-category is a row, not a deploy.
--
--   parent_code       NULL for the four top-level categories
--   name_fr/en        24 characters at most — a WhatsApp list title is cut there
--   hint_fr/en        72 characters at most — the list-row description limit
--   required/optional_documents  [{ code, label_fr, label_en }]
--   extra_fields      [{ key, type, required, label_*, prompt_*, ... }]
--   guarantee_codes   plan coverage codes this claim type falls under; NULL when
--                     no guarantee maps to it, and the coverage check is skipped
--
-- SAFETY: new table, and INSERT IGNORE on the unique code — re-running never
-- overwrites a category the client has edited.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS \`claim_categories\` (
  \`id\` INT NOT NULL AUTO_INCREMENT,
  \`code\` VARCHAR(60) NOT NULL,
  \`parent_code\` VARCHAR(60) NULL,
  \`name_fr\` VARCHAR(60) NOT NULL,
  \`name_en\` VARCHAR(60) NOT NULL,
  \`hint_fr\` VARCHAR(120) NULL,
  \`hint_en\` VARCHAR(120) NULL,
  \`required_documents\` JSON NULL,
  \`optional_documents\` JSON NULL,
  \`extra_fields\` JSON NULL,
  \`default_priority\` ENUM('normal','high','urgent') NOT NULL DEFAULT 'normal',
  \`guarantee_codes\` JSON NULL,
  \`active\` TINYINT(1) NOT NULL DEFAULT 1,
  \`sort_order\` INT NOT NULL DEFAULT 0,
  \`updated_by_user_id\` INT NULL,
  \`created_at\` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  \`updated_at\` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (\`id\`),
  UNIQUE KEY \`uq_claim_category_code\` (\`code\`),
  KEY \`ix_claim_category_parent\` (\`parent_code\`, \`sort_order\`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

INSERT IGNORE INTO \`claim_categories\`
  (\`code\`, \`parent_code\`, \`name_fr\`, \`name_en\`, \`hint_fr\`, \`hint_en\`,
   \`required_documents\`, \`optional_documents\`, \`extra_fields\`,
   \`default_priority\`, \`guarantee_codes\`, \`active\`, \`sort_order\`) VALUES
${DEFAULT_CATEGORIES.map(
  (c) =>
    `  (${q(c.code)}, ${q(c.parent_code)}, ${q(c.name_fr)}, ${q(c.name_en)}, ${q(c.hint_fr)}, ${q(c.hint_en)},\n` +
    `   ${j(c.required_documents)},\n   ${j(c.optional_documents)},\n   ${j(c.extra_fields)},\n` +
    `   ${q(c.default_priority)}, ${j(c.guarantee_codes)}, 1, ${Number(c.sort_order) || 0})`
).join(",\n")};
`;

const claimKeys = Object.keys(SETTING_REGISTRY).filter((k) => k.startsWith("claims."));
const settingsSql = `-- ----------------------------------------------------------------------------
-- Milestone 4 — every claims rule the client controls, as settings.
--
-- GENERATED by scripts/generateClaimSeed.js from SETTING_REGISTRY in
-- models/settingsModel.js, which is what governs reads and writes. Do not edit
-- by hand.
--
-- Each row carries a working default, so nothing in the claims flow waits on a
-- client answer: consent text empty means the consent step is skipped;
-- notification emails empty means claims wait in the dashboard; retention empty
-- means documents are kept.
--
-- SAFETY: INSERT IGNORE on the unique setting_key. Re-running changes nothing and
-- never overwrites a value the client has saved.
-- ----------------------------------------------------------------------------
INSERT IGNORE INTO \`app_settings\` (\`setting_key\`, \`setting_value\`, \`value_type\`, \`is_secret\`, \`description\`) VALUES
${claimKeys
  .map((k) => {
    const d = SETTING_REGISTRY[k];
    const value = d.default === undefined || d.default === null ? null : String(d.default);
    return `  (${q(k)}, ${q(value)}, ${q(d.type)}, ${d.secret ? 1 : 0}, ${q(d.description)})`;
  })
  .join(",\n")};
`;

fs.writeFileSync(path.join(dir, "m4_03_claim_categories.sql"), categoriesSql);
fs.writeFileSync(path.join(dir, "m4_08_claim_settings.sql"), settingsSql);
console.log(`m4_03: ${DEFAULT_CATEGORIES.length} categories · m4_08: ${claimKeys.length} settings`);
